#!/usr/bin/env python3
"""Extracts the capture times of a Wingtra flight for the injector (ADR-003).

The WingtraHub project file (<flight>.json) holds two geotag lists:

* "Raw": the autopilot's camera trigger log, in milliseconds since the
  Unix epoch;
* "ProcessedForward": the PPK solution at the camera event marks, with
  the event time in milliseconds since the Unix epoch and the reported
  position accuracy.

The capture time is the event mark time of the PPK solution, the instant
at which the positions of the pose files hold. On Dorfberg Flight 01 the
trigger log is 70 to 190 ms later (median 120 ms); it is not used.

The geotag sequence numbers are matched to the image names of the geotag
CSV by their coordinates, so no numbering rule is assumed.

Output (one line per image of the CSV):

    capture <image> <utc_ms> <h_accuracy_m> <v_accuracy_m>

Usage:
    extract_capture_times.py <flight.json> <geotags.csv> <output>

Only the Python standard library is used.
"""

import argparse
import csv
import json
import sys
from pathlib import Path


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("flight_json", type=Path)
    ap.add_argument("geotags", type=Path)
    ap.add_argument("output", type=Path)
    args = ap.parse_args()

    flights = {f["name"]: f["geotag"] for f in json.loads(args.flight_json.read_text())["flights"]}
    if "ProcessedForward" not in flights:
        sys.exit(f"{args.flight_json}: no ProcessedForward geotags (PPK solution)")
    events = flights["ProcessedForward"]

    with open(args.geotags, encoding="utf-8") as f:
        rows = [r for r in csv.reader(f) if r and not r[0].startswith("#")]

    lines = []
    for row in rows:
        name, lon, lat = row[0], float(row[1]), float(row[2])
        match = [e for e in events
                 if abs(float(e["coordinate"][0]) - lat) < 1e-9 and abs(float(e["coordinate"][1]) - lon) < 1e-9]
        if len(match) != 1:
            sys.exit(f"{name}: {len(match)} geotags with its coordinates")
        e = match[0]
        lines.append(f"capture {name} {int(e['timestamp'])} {float(e['hAccuracy']):.3f} {float(e['vAccuracy']):.3f}")

    times = [int(line.split()[2]) for line in lines]
    if any(b <= a for a, b in zip(times, times[1:])):
        sys.exit("capture times are not strictly increasing in image order")

    header = [
        "# Capture times of the images (ADR-003, ADR-014).",
        "# Generated by tools/dataset/extract_capture_times.py; do not edit.",
        f"# Source: {args.flight_json.name}, geotags ProcessedForward (PPK event marks).",
        "#",
        "# capture image utc_ms h_accuracy_m v_accuracy_m",
    ]
    args.output.write_text("\n".join(header + lines) + "\n")
    print(f"{len(lines)} capture times, {(times[-1] - times[0]) / 1000.0:.1f} s, written to {args.output}")


if __name__ == "__main__":
    main()
