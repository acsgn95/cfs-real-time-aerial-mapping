#!/usr/bin/env python3
"""Extracts camera poses and calibration from a Metashape project.

Writes the bundle-adjusted ("optimized", ADR-003) camera poses of all
aligned images and the calibration, converted to OrthoStream conventions:

* camera model: OpenCV pinhole with k1, k2, k3, p1, p2, top-left pixel
  centre at (0, 0) (ADR-008 section 2);
* poses: camera centre in WGS 84 / ETRS89 ECEF and the rotation q_E_C
  (camera to ECEF) as a Hamilton quaternion w, x, y, z with w >= 0
  (ADR-004 section 2). Camera axes: x right, y down, z forward.

The chunk transform of the project maps to the geocentric frame of the
project CRS's datum; the datum translation (TOWGS84) completes the step to
ECEF (ADR-008 section 3). The conversion is the one verified by the ground
control point check of libs/geo.

Usage:
    extract_metashape_poses.py <chunk.zip> <output file> [--towgs84 dx dy dz]

The default translation is that of CH1903+ (Dorfberg). Only the Python
standard library is used.
"""

import argparse
import math
import sys
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

CH1903PLUS_TOWGS84 = (674.374, 15.056, 405.346)


def matmul(a, b):
    return [[sum(a[i][k] * b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]


def matvec(a, v):
    return [sum(a[i][k] * v[k] for k in range(3)) for i in range(3)]


def quaternion(r):
    """Hamilton quaternion (w, x, y, z) of a rotation matrix, w >= 0."""
    trace = r[0][0] + r[1][1] + r[2][2]
    if trace > 0.0:
        s = 2.0 * math.sqrt(trace + 1.0)
        q = (0.25 * s, (r[2][1] - r[1][2]) / s, (r[0][2] - r[2][0]) / s, (r[1][0] - r[0][1]) / s)
    elif r[0][0] > r[1][1] and r[0][0] > r[2][2]:
        s = 2.0 * math.sqrt(1.0 + r[0][0] - r[1][1] - r[2][2])
        q = ((r[2][1] - r[1][2]) / s, 0.25 * s, (r[0][1] + r[1][0]) / s, (r[0][2] + r[2][0]) / s)
    elif r[1][1] > r[2][2]:
        s = 2.0 * math.sqrt(1.0 + r[1][1] - r[0][0] - r[2][2])
        q = ((r[0][2] - r[2][0]) / s, (r[0][1] + r[1][0]) / s, 0.25 * s, (r[1][2] + r[2][1]) / s)
    else:
        s = 2.0 * math.sqrt(1.0 + r[2][2] - r[0][0] - r[1][1])
        q = ((r[1][0] - r[0][1]) / s, (r[0][2] + r[2][0]) / s, (r[1][2] + r[2][1]) / s, 0.25 * s)
    norm = math.sqrt(sum(c * c for c in q))
    q = tuple(c / norm for c in q)
    return q if q[0] >= 0.0 else tuple(-c for c in q)


def orthonormality_error(r):
    rt_r = matmul([list(col) for col in zip(*r)], r)
    return max(abs(rt_r[i][j] - (1.0 if i == j else 0.0)) for i in range(3) for j in range(3))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("chunk_zip", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--towgs84", type=float, nargs=3, default=CH1903PLUS_TOWGS84, metavar=("DX", "DY", "DZ"))
    args = parser.parse_args()

    with zipfile.ZipFile(args.chunk_zip) as zf:
        chunk = ET.fromstring(zf.read("doc.xml"))

    sensors = list(chunk.find("sensors").iter("sensor"))
    if len(sensors) != 1:
        raise SystemExit(f"expected one sensor, found {len(sensors)}")
    sensor = sensors[0]
    calib = next(c for c in sensor.iter("calibration") if c.get("class") == "adjusted")

    def value(tag):
        node = calib.find(tag)
        return float(node.text) if node is not None else 0.0

    for unsupported in ("k4", "b1", "b2"):
        if value(unsupported) != 0.0:
            raise SystemExit(f"calibration term {unsupported} is not zero")
    width = int(calib.find("resolution").get("width"))
    height = int(calib.find("resolution").get("height"))
    f = value("f")
    # ADR-008: Metashape to OpenCV.
    cx = width / 2 + value("cx") - 0.5
    cy = height / 2 + value("cy") - 0.5
    k1, k2, k3 = value("k1"), value("k2"), value("k3")
    p1, p2 = value("p2"), value("p1")

    transform = chunk.find("transform")
    scale = float(transform.find("scale").text)
    rot_values = [float(v) for v in transform.find("rotation").text.split()]
    r_chunk = [rot_values[0:3], rot_values[3:6], rot_values[6:9]]
    t_chunk = [float(v) for v in transform.find("translation").text.split()]
    if orthonormality_error(r_chunk) > 1e-9:
        raise SystemExit("chunk rotation is not orthonormal")

    lines = [
        "# Camera poses and calibration extracted from a Metashape project.",
        "# Generated by tools/dataset/extract_metashape_poses.py; do not edit.",
        f"# Source: {args.chunk_zip.name}; datum translation to ECEF: {' '.join(repr(v) for v in args.towgs84)}",
        "#",
        "# camera width height fx fy cx cy k1 k2 k3 p1 p2",
        "#   OpenCV model; centre of the top-left pixel at (0, 0).",
        "# pose image x y z qw qx qy qz",
        "#   camera centre in ECEF (m) and q_E_C (camera to ECEF), Hamilton, w >= 0.",
        f"camera {width} {height} {f!r} {f!r} {cx!r} {cy!r} {k1!r} {k2!r} {k3!r} {p1!r} {p2!r}",
    ]

    count = skipped = 0
    for cam in chunk.find("cameras").iter("camera"):
        node = cam.find("transform")
        if node is None:
            skipped += 1  # not aligned
            continue
        if cam.get("sensor_id", "0") != sensor.get("id"):
            raise SystemExit(f"camera {cam.get('label')} uses another sensor")
        m = [float(v) for v in node.text.split()]
        r_cam = [m[0:3], m[4:7], m[8:11]]
        t_cam = [m[3], m[7], m[11]]
        if orthonormality_error(r_cam) > 1e-9:
            raise SystemExit(f"rotation of camera {cam.get('label')} is not orthonormal")
        r_e_c = matmul(r_chunk, r_cam)
        centre = [scale * v + t + d for v, t, d in zip(matvec(r_chunk, t_cam), t_chunk, args.towgs84)]
        q = quaternion(r_e_c)
        lines.append(
            "pose " + cam.get("label") + " " + " ".join(f"{v:.4f}" for v in centre) + " "
            + " ".join(f"{v:.12f}" for v in q)
        )
        count += 1

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n")
    print(f"{count} poses ({skipped} cameras not aligned) -> {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
