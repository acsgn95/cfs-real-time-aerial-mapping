#!/usr/bin/env python3
"""Extracts the ground control point test fixture of ADR-008 section 2.

Reads the Metashape project files and the ground control point file of
Dorfberg Flight 01 and writes a small text file for the geo library tests:
the adjusted calibration, the chunk transform, the five ground control
points, the 25 marker observations, the poses of the cameras that observe
them, and the per-point results of the Metashape report.

Usage:
    extract_dorfberg_gcp.py <dataset dir> <output file>

The dataset directory must contain chunk.zip, frame.zip and
20201109_Dorfberg.txt (Bühler, Stoffel and Salzmann 2022, Photogrammetric
Drone Data Dorfberg, EnviDat, doi:10.16904/envidat.376, ODbL with DbCL).
Only the Python standard library is used.
"""

import csv
import sys
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

# CH1903+ is CHTRS95 shifted by this translation; it is the TOWGS84 term of
# the Metashape project CRS (ADR-008 section 3).
TOWGS84 = (674.374, 15.056, 405.346)

# Table 6 "Check points" of Dorfberg_20201109_Report.pdf (page 6):
# label: (image error px, X error cm, Y error cm, Z error cm), where X is
# easting, Y northing and Z altitude, as estimated minus surveyed.
REPORT_CHECK_POINTS = {
    "1": (0.283, 0.365631, 0.722336, 5.21698),
    "2": (0.178, 3.07828, -1.27077, 3.81544),
    "3": (0.437, 3.35995, -3.43102, 9.05842),
    "4": (0.336, -0.104451, -2.61665, 3.15021),
    "5": (0.345, 2.79781, -12.3455, 11.0872),
}


def read_xml(archive: Path) -> ET.Element:
    with zipfile.ZipFile(archive) as zf:
        return ET.fromstring(zf.read("doc.xml"))


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    data_dir, out_path = Path(sys.argv[1]), Path(sys.argv[2])

    chunk = read_xml(data_dir / "chunk.zip")
    frame = read_xml(data_dir / "frame.zip")

    sensor = chunk.find("sensors/sensor")
    resolution = sensor.find("resolution")
    calib = next(c for c in sensor.iter("calibration") if c.get("class") == "adjusted")

    def calib_value(tag: str) -> str:
        node = calib.find(tag)
        return node.text if node is not None else "0"

    for unsupported in ("k4", "b1", "b2"):
        if float(calib_value(unsupported)) != 0.0:
            raise SystemExit(f"calibration term {unsupported} is not zero")

    transform = chunk.find("transform")
    cameras = {
        c.get("id"): (c.get("label"), c.find("transform").text.split())
        for c in chunk.find("cameras").iter("camera")
        if c.find("transform") is not None
    }
    marker_labels = {m.get("id"): m.get("label") for m in chunk.find("markers").iter("marker")}

    with open(data_dir / "20201109_Dorfberg.txt", newline="") as fh:
        gcps = {row["Name"]: (row["ECEF X"], row["ECEF Y"], row["ECEF Z"]) for row in csv.DictReader(fh)}

    lines = [
        "# Dorfberg Flight 01 ground control point fixture (ADR-008 section 2).",
        "# Generated by tools/fixtures/extract_dorfberg_gcp.py; do not edit.",
        "# Source: Buehler, Stoffel and Salzmann (2022), Photogrammetric Drone Data",
        "# Dorfberg, EnviDat, doi:10.16904/envidat.376, licensed under ODbL with DbCL.",
        "#",
        "# metashape_calibration width height f cx cy k1 k2 k3 p1 p2",
        "#   Metashape convention: principal point as offset from the image centre,",
        "#   centre of the top-left pixel at (0.5, 0.5).",
        "# chunk_transform scale r00 r01 r02 r10 r11 r12 r20 r21 r22 tx ty tz",
        "#   chunk frame to the geocentric frame of CH1903+: X = scale * R * x + t.",
        "# towgs84 dx dy dz",
        "#   CH1903+ geocentric to ETRS89 / WGS 84 geocentric (translation).",
        "# gcp label x y z",
        "#   surveyed position, ETRS89 ECEF in metres.",
        "# report label image_error_px easting_cm northing_cm altitude_cm",
        "#   Metashape report, table 6: estimated minus surveyed.",
        "# camera label r00 r01 r02 r10 r11 r12 r20 r21 r22 tx ty tz",
        "#   camera to chunk frame; camera axes x right, y down, z forward.",
        "# marker gcp_label camera_label u v",
        "#   marker position in Metashape pixel coordinates.",
        " ".join(["metashape_calibration", resolution.get("width"), resolution.get("height")]
                 + [calib_value(t) for t in ("f", "cx", "cy", "k1", "k2", "k3", "p1", "p2")]),
        " ".join(["chunk_transform", transform.find("scale").text]
                 + transform.find("rotation").text.split()
                 + transform.find("translation").text.split()),
        " ".join(["towgs84"] + [repr(v) for v in TOWGS84]),
    ]
    for label in sorted(gcps):
        lines.append(" ".join(["gcp", label, *gcps[label]]))
    for label in sorted(REPORT_CHECK_POINTS):
        lines.append(" ".join(["report", label] + [repr(v) for v in REPORT_CHECK_POINTS[label]]))

    observations = []
    used_cameras = set()
    for marker in frame.find("markers").iter("marker"):
        label = marker_labels[marker.get("marker_id")]
        for loc in marker.iter("location"):
            cam_label, _ = cameras[loc.get("camera_id")]
            used_cameras.add(loc.get("camera_id"))
            observations.append(" ".join(["marker", label, cam_label, loc.get("x"), loc.get("y")]))

    for cam_id in sorted(used_cameras, key=int):
        cam_label, matrix = cameras[cam_id]
        rows = [matrix[0:3], matrix[4:7], matrix[8:11]]
        translation = [matrix[3], matrix[7], matrix[11]]
        lines.append(" ".join(["camera", cam_label] + [v for r in rows for v in r] + translation))
    lines.extend(observations)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n")
    print(f"{len(used_cameras)} cameras, {len(observations)} observations -> {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
