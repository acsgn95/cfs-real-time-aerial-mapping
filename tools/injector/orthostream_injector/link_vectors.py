"""Byte vectors of the link format, shared by the Python and C tests.

interfaces/link/test_vectors.txt is written from VECTORS by
`python3 -m orthostream_injector.link_vectors <output>`. The Python test
checks that the encoder still produces the file; libs/link/tests decodes the
file and checks the values listed in docs/interfaces/link.md.
"""

import sys
from pathlib import Path

from . import link

TELEMETRY = link.Telemetry(
    time_ns=1763078400123456789,
    recorded_ns=1604917662246000000,
    latitude_deg=46.8238423310124,
    longitude_deg=9.827941140558746,
    height_m=2582.535681044683,
    q_n_b=(0.5, 0.5, -0.5, 0.5),
    std_position_m=(0.03, 0.03, 0.05),
    std_attitude_deg=(1.0, 1.0, 3.0),
    fix=6,
    session_id=7,
)

SESSION = link.SessionStart(
    session_id=7,
    start_ns=1763078400000000000,
    recorded_start_ns=1604917662246000000,
    time_factor=1.0,
    width=7952,
    height=5304,
    k=(7466.670812412861, 7466.670812412861, 3960.1782422883352, 2637.8310591480517),
    distortion=(-0.011379646133417727, 0.05104158467607952, -0.09318594764822886, -1.424956079674974e-05,
                -4.833588644189338e-05),
    q_b_c=(0.7071067811865476, 0.0, 0.0, 0.7071067811865476),
    t_b_c=(0.1, 0.0, 0.05),
    camera_name="RX1RII 42MP",
)

IMAGE = link.Image(session_id=7, image_seq=3, capture_ns=1763078401580000000, recorded_ns=1604917663826000000,
                   data=bytes([0xFF, 0xD8, 0xFF, 0xD9]))

VECTORS = [
    ("telemetry", link.telemetry(TELEMETRY, sequence=42)),
    ("heartbeat", link.heartbeat(1763078401000000000, 7, 10, 1, sequence=43)),
    ("session_start", link.session_start(SESSION, sequence=0)),
    ("image", link.image_head(IMAGE, sequence=1) + IMAGE.data),
    ("session_end", link.session_end(7, 1, 1763078402000000000, sequence=2)),
]


def render():
    lines = [
        "# Byte vectors of the link format (docs/interfaces/link.md).",
        "# Generated by tools/injector/orthostream_injector/link_vectors.py; do not edit.",
        "# name hex",
    ]
    lines += [f"{name} {data.hex()}" for name, data in VECTORS]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    Path(sys.argv[1]).write_text(render())
